#!/usr/bin/env node
/**
 * Converts supabase-export.json into migration-import.sql for Cloudflare D1.
 * Chunks images and long post bodies so every SQL statement stays safely under
 * Cloudflare D1's 100 KB statement length limit (prevents SQLITE_TOOBIG).
 *
 * Usage (PowerShell):
 *   $env:MIGRATION_PASSWORD="TempLoginPassword123"
 *   node scripts/import-to-d1.mjs
 *   npx wrangler d1 execute arkive-db --remote --file=migration-import.sql
 */

import { webcrypto } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'fs';

const crypto = webcrypto;
const INPUT_FILE = 'supabase-export.json';
const OUTPUT_SQL = 'migration-import.sql';
const MEDIA_CHUNK_BYTES = 30 * 1024; // 30 KB binary = 60 KB hex (well under 100 KB D1 SQL limit)
const TEXT_CHUNK_CHARS = 30000;
const MAX_D1_MEDIA_IMPORT_BYTES = 5 * 1024 * 1024; // 5 MB

if (!existsSync(INPUT_FILE)) {
  console.error(`Missing ${INPUT_FILE}. Run "node scripts/export-supabase.mjs" first.`);
  process.exit(1);
}

function sqlStr(val) {
  if (val === null || val === undefined) return 'NULL';
  return `'${String(val).replace(/'/g, "''")}'`;
}

function sqlInt(val) {
  return val ? '1' : '0';
}

async function hashPassword(password) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const keyMaterial = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(password),
    'PBKDF2',
    false,
    ['deriveBits']
  );
  const derivedBits = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', salt, iterations: 100000, hash: 'SHA-256' },
    keyMaterial,
    256
  );
  const saltB64 = Buffer.from(salt).toString('base64');
  const hashB64 = Buffer.from(derivedBits).toString('base64');
  return `${saltB64}:${hashB64}`;
}

function rewriteSupabaseImageUrls(text, sourceUrl) {
  if (!text || typeof text !== 'string') return text;
  if (sourceUrl) {
    const escaped = sourceUrl.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(`${escaped}/storage/v1/object/public/post-images/([^"'\\s)]+)`, 'g');
    text = text.replace(re, '/api/images/serve/$1');
  }
  return text.replace(
    /https:\/\/[a-z0-9-]+\.supabase\.co\/storage\/v1\/object\/public\/post-images\/([^"'\s)]+)/gi,
    '/api/images/serve/$1'
  );
}

function splitChunks(str, size) {
  if (!str) return [''];
  const out = [];
  for (let i = 0; i < str.length; i += size) {
    out.push(str.slice(i, i + size));
  }
  return out;
}

async function main() {
  const data = JSON.parse(readFileSync(INPUT_FILE, 'utf8'));
  const tempPassword = (process.env.MIGRATION_PASSWORD || '').trim();

  if (tempPassword && tempPassword.length < 6) {
    console.error('MIGRATION_PASSWORD must be at least 6 characters.');
    process.exit(1);
  }

  const defaultHash = tempPassword
    ? await hashPassword(tempPassword)
    : `MIGRATION_LOCKED:${Buffer.from(crypto.getRandomValues(new Uint8Array(16))).toString('hex')}`;

  const lines = [
    '-- Generated by scripts/import-to-d1.mjs',
    '-- Run: npx wrangler d1 execute arkive-db --remote --file=migration-import.sql',
    'CREATE TABLE IF NOT EXISTS media_chunks (key TEXT NOT NULL REFERENCES media(key) ON DELETE CASCADE, idx INTEGER NOT NULL, data BLOB NOT NULL, PRIMARY KEY (key, idx));',
    '',
  ];

  const userMap = new Map();
  for (const u of data.users || []) {
    userMap.set(u.id, {
      id: u.id,
      email: (u.email || `${u.id}@migrated.local`).toLowerCase(),
      created_at: u.created_at || new Date().toISOString(),
    });
  }
  for (const p of data.profiles || []) {
    if (!userMap.has(p.id)) {
      userMap.set(p.id, {
        id: p.id,
        email: `${p.username || p.id}@migrated.local`.toLowerCase(),
        created_at: p.created_at || new Date().toISOString(),
      });
    }
  }

  for (const u of userMap.values()) {
    lines.push(
      `INSERT OR IGNORE INTO users (id, email, password_hash, created_at) VALUES (${sqlStr(u.id)}, ${sqlStr(u.email)}, ${sqlStr(defaultHash)}, ${sqlStr(u.created_at)});`
    );
  }

  for (const p of data.profiles || []) {
    const avatarUrl = rewriteSupabaseImageUrls(p.avatar_url, data.source_supabase_url);
    lines.push(
      `INSERT OR IGNORE INTO profiles (id, username, display_name, avatar_url, created_at) VALUES (${sqlStr(p.id)}, ${sqlStr(p.username)}, ${sqlStr(p.display_name || p.username)}, ${sqlStr(avatarUrl)}, ${sqlStr(p.created_at || new Date().toISOString())});`
    );
  }

  for (const t of data.tags || []) {
    lines.push(
      `INSERT OR IGNORE INTO tags (id, user_id, name, pill_color, text_color, created_at) VALUES (${sqlStr(t.id)}, ${sqlStr(t.user_id)}, ${sqlStr(t.name)}, ${sqlStr(t.pill_color || '#3b82f6')}, ${sqlStr(t.text_color || '#ffffff')}, ${sqlStr(t.created_at || new Date().toISOString())});`
    );
  }

  for (const s of data.spaces || []) {
    lines.push(
      `INSERT OR IGNORE INTO spaces (id, user_id, name, icon, tag_id, show_in_menu, share_link, created_at) VALUES (${sqlStr(s.id)}, ${sqlStr(s.user_id)}, ${sqlStr(s.name)}, ${sqlStr(s.icon || '📁')}, ${sqlStr(s.tag_id || null)}, ${sqlInt(s.show_in_menu !== false)}, ${sqlStr(s.share_link)}, ${sqlStr(s.created_at || new Date().toISOString())});`
    );
  }

  for (const sm of data.space_members || []) {
    lines.push(
      `INSERT OR IGNORE INTO space_members (id, space_id, member_username, added_by, created_at) VALUES (${sqlStr(sm.id)}, ${sqlStr(sm.space_id)}, ${sqlStr(sm.member_username)}, ${sqlStr(sm.added_by)}, ${sqlStr(sm.created_at || new Date().toISOString())});`
    );
  }

  for (const post of data.posts || []) {
    const rewrittenBody = post.passphrase_hash
      ? ''
      : rewriteSupabaseImageUrls(post.body || '', data.source_supabase_url);
    const encBody = post.encrypted_body || null;

    const bodyChunks = splitChunks(rewrittenBody, TEXT_CHUNK_CHARS);
    const encChunks = encBody ? splitChunks(encBody, TEXT_CHUNK_CHARS) : [null];
    const needsChunking = bodyChunks.length > 1 || encChunks.length > 1;

    if (needsChunking) {
      lines.push(
        `INSERT INTO posts (id, user_id, title, subtitle, body, is_markdown, is_draft, is_pinned, passphrase_hash, encrypted_body, date_tag, space_id, created_at, updated_at) VALUES (${sqlStr(post.id)}, ${sqlStr(post.user_id)}, ${sqlStr(post.title || '')}, ${sqlStr(post.subtitle || '')}, ${sqlStr(bodyChunks[0])}, ${sqlInt(post.is_markdown)}, ${sqlInt(post.is_draft)}, ${sqlInt(post.is_pinned)}, ${sqlStr(post.passphrase_hash || null)}, ${sqlStr(encChunks[0])}, ${sqlStr(post.date_tag || null)}, ${sqlStr(post.space_id || null)}, ${sqlStr(post.created_at || new Date().toISOString())}, ${sqlStr(post.updated_at || post.created_at || new Date().toISOString())}) ON CONFLICT(id) DO UPDATE SET body = excluded.body, encrypted_body = excluded.encrypted_body;`
      );
      for (let i = 1; i < bodyChunks.length; i++) {
        lines.push(`UPDATE posts SET body = body || ${sqlStr(bodyChunks[i])} WHERE id = ${sqlStr(post.id)};`);
      }
      for (let i = 1; i < encChunks.length; i++) {
        lines.push(`UPDATE posts SET encrypted_body = encrypted_body || ${sqlStr(encChunks[i])} WHERE id = ${sqlStr(post.id)};`);
      }
    } else {
      lines.push(
        `INSERT OR IGNORE INTO posts (id, user_id, title, subtitle, body, is_markdown, is_draft, is_pinned, passphrase_hash, encrypted_body, date_tag, space_id, created_at, updated_at) VALUES (${sqlStr(post.id)}, ${sqlStr(post.user_id)}, ${sqlStr(post.title || '')}, ${sqlStr(post.subtitle || '')}, ${sqlStr(rewrittenBody)}, ${sqlInt(post.is_markdown)}, ${sqlInt(post.is_draft)}, ${sqlInt(post.is_pinned)}, ${sqlStr(post.passphrase_hash || null)}, ${sqlStr(encBody)}, ${sqlStr(post.date_tag || null)}, ${sqlStr(post.space_id || null)}, ${sqlStr(post.created_at || new Date().toISOString())}, ${sqlStr(post.updated_at || post.created_at || new Date().toISOString())});`
      );
    }
  }

  for (const pt of data.post_tags || []) {
    lines.push(
      `INSERT OR IGNORE INTO post_tags (post_id, tag_id) VALUES (${sqlStr(pt.post_id)}, ${sqlStr(pt.tag_id)});`
    );
  }

  let d1Images = 0;
  const r2Uploads = [];
  for (const img of data.images || []) {
    if (!existsSync(img.localPath)) continue;
    const buf = readFileSync(img.localPath);
    const ownerId = img.key.split('/')[0];
    if (!userMap.has(ownerId)) continue;

    if (buf.byteLength <= MAX_D1_MEDIA_IMPORT_BYTES) {
      d1Images++;
      lines.push(`DELETE FROM media WHERE key = ${sqlStr(img.key)};`);
      if (buf.byteLength <= MEDIA_CHUNK_BYTES) {
        lines.push(
          `INSERT INTO media (key, user_id, content_type, data) VALUES (${sqlStr(img.key)}, ${sqlStr(ownerId)}, ${sqlStr(img.mimeType || 'image/png')}, X'${buf.toString('hex')}');`
        );
      } else {
        lines.push(
          `INSERT INTO media (key, user_id, content_type, data) VALUES (${sqlStr(img.key)}, ${sqlStr(ownerId)}, ${sqlStr(img.mimeType || 'image/png')}, X'');`
        );
        let idx = 0;
        for (let offset = 0; offset < buf.byteLength; offset += MEDIA_CHUNK_BYTES) {
          const slice = buf.subarray(offset, offset + MEDIA_CHUNK_BYTES);
          lines.push(
            `INSERT INTO media_chunks (key, idx, data) VALUES (${sqlStr(img.key)}, ${idx}, X'${slice.toString('hex')}');`
          );
          idx++;
        }
      }
    } else {
      r2Uploads.push(img);
    }
  }

  writeFileSync(OUTPUT_SQL, lines.join('\n') + '\n');

  console.log(`\nGenerated ${OUTPUT_SQL} successfully!`);
  console.log(`  Users: ${userMap.size}`);
  console.log(`  Profiles: ${(data.profiles || []).length}`);
  console.log(`  Tags: ${(data.tags || []).length}`);
  console.log(`  Spaces: ${(data.spaces || []).length}`);
  console.log(`  Posts: ${(data.posts || []).length}`);
  console.log(`  D1 media images: ${d1Images}`);

  if (r2Uploads.length > 0) {
    console.log(`\n${r2Uploads.length} image(s) exceeded 5 MB and should be uploaded to R2:`);
    for (const img of r2Uploads) {
      console.log(`  npx wrangler r2 object put arkive-images/${img.key} --file="${img.localPath}" --content-type="${img.mimeType}"`);
    }
  }

  console.log('\nNext step:');
  console.log(`  npx wrangler d1 execute arkive-db --remote --file=${OUTPUT_SQL}`);
  if (tempPassword) {
    console.log('  Then sign in with your email and MIGRATION_PASSWORD, and update your password in Profile settings.');
  } else {
    console.log('  Then set a password for each migrated account with: node scripts/reset-password.mjs <email> <new-password> --remote');
  }
}

main().catch((err) => {
  console.error('\nImport generation failed:', err.message);
  process.exit(1);
});
